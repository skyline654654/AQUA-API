// 本文件内置一套自制的 5×7 位图字体。
//
// 意图（Why）：
//
//	渲染棋盘需要画坐标字母（A..T，19 路）与顶部信息条文字，
//	但本仓库约束"只能引入纯 Go 依赖"，且为标准库之外的一个字体
//	拉进 golang.org/x/image 并不划算——本项目只需要 40 来个字形。
//
//	因此手写一张 5×7 位图表：每个字形 7 行、每行 5 位（位 4 为最左列）。
//	体积可忽略、零依赖、且完全可控——需要什么字形就补什么，
//	不存在"字体文件里有没有这个字"的不确定性。
//
//	注意 glyphWidth/glyphHeight 是【逻辑像素】，实际渲染时会按倍数放大
//	（见 render.go 的 drawText）。位图放大后有明显锯齿，但我们先做了
//	2 倍超采样再降采样，最终边缘是平滑的。
//
// 流转（Flow）：
//
//	render.go drawText → bitmapFont[r] → 逐位绘制
//
// 扩展（Extend）：
//
//	需要新字形：在下方 map 里按 7 行 5 位的格式补一条即可；
//	未知字形渲染为 '?'（见 drawText），不会静默消失——
//	坐标标签缺一个字母会让整列定位错位，画成方框至少看得出来。
