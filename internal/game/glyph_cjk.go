// 本文件内嵌象棋棋子的汉字字形（32x32 灰度位图，每像素 4 bit 覆盖度）。
//
// 意图（Why）：
//
//	象棋棋子必须写标准汉字（将士象马车炮兵卒 / 帅仕相马车炮砲卒），
//	用拉丁字母替代会破坏棋子的辨识习惯——用户第一眼就会觉得"这不是象棋"。
//
//	但 Go 侧渲染没有可用字体：本仓库约束"只引入纯 Go 依赖"，
//	而 CJK 字体动辄十几 MB，也不可能把系统字体（Windows 的宋体/MSYH）
//	打进仓库或塞进容器镜像。因此把这 12 个标准汉字的点位固化成数据。
//
//	为什么用【灰度】而不是 1-bit 黑白：
//	  中文笔画在 32px 下只有 1~2 像素宽，二值化会随机切断笔画
//	  （实测「士」的横、「车」的竖都会被切断）。保留 16 级覆盖度、
//	  在渲染时按 alpha 混合，字形才平滑可读。
//
//	字形来源：宋体（SimSun）在 32px 下的光栅化结果，中宫收紧、笔画平直，
//	正是传统象棋棋子的字体气质。这些是标准汉字的基本字形，
//	32 像素下的写法几乎没有其他选择（窄笔画字形的必然形态）。
//
// 流转（Flow）：
//
//	render.go drawXiangqiPiece → xiangqiGlyph(piece, color) 取字符
//	  → cjkGlyph 查表 → drawGlyphGray 按覆盖度 alpha 混合到棋子圆盘上
//
// 扩展（Extend）：
//
//	需要新字形（如繁体「車」「馬」）：在本表补一条即可，
//	渲染侧无需改动。字形尺寸变化时同步 cjkGlyphSize。
